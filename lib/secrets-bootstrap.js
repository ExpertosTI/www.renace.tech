/**
 * Auto-generate cryptographically strong secrets when missing.
 * Persists to data/generated-secrets.json (volume) so values survive restarts.
 * Never overwrites a secret that is already set to a real (non-placeholder) value.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const PLACEHOLDER_RE =
  /^(?:change[_-]?me|your[-_]|tu[_-]|random-string|example|xxx+|TODO|FIXME|replace|changethis).*$/i;

const AUTO_KEYS = [
  { key: 'ADMIN_TOKEN', bytes: 32 },
  { key: 'ADMIN_ACCESS_PASSWORD', bytes: 24 },
  { key: 'ADMIN_SESSION_SECRET', bytes: 32 },
  { key: 'PARTICIPANT_SESSION_SECRET', bytes: 32 },
  { key: 'PORTAL_ENCRYPTION_KEY', bytes: 32 },
  { key: 'NOTIFY_API_KEY', bytes: 24 },
];

function isPlaceholder(value) {
  if (value == null) return true;
  const v = String(value).trim();
  if (!v) return true;
  if (v.length < 12) return true;
  if (PLACEHOLDER_RE.test(v)) return true;
  return false;
}

function generateSecret(bytes = 32) {
  // url-safe base64 without padding — strong & easy to put in env files
  return crypto.randomBytes(bytes).toString('base64url');
}

function secretsFilePath(dataDir) {
  return path.join(dataDir, 'generated-secrets.json');
}

function loadPersisted(filePath) {
  try {
    if (!fs.existsSync(filePath)) return {};
    const raw = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    return raw && typeof raw === 'object' ? raw : {};
  } catch {
    return {};
  }
}

function savePersisted(filePath, data) {
  const dir = path.dirname(filePath);
  fs.mkdirSync(dir, { recursive: true });
  const tmp = `${filePath}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, `${JSON.stringify(data, null, 2)}\n`, { encoding: 'utf8', mode: 0o600 });
  fs.renameSync(tmp, filePath);
  try { fs.chmodSync(filePath, 0o600); } catch (_) {}
}

/**
 * Ensure required secrets exist on process.env.
 * @returns {{ generated: string[], reused: string[], file: string }}
 */
function bootstrapSecrets(options = {}) {
  const dataDir = options.dataDir || path.join(__dirname, '..', 'data');
  const filePath = secretsFilePath(dataDir);
  const persisted = loadPersisted(filePath);
  const generated = [];
  const reused = [];
  let dirty = false;

  for (const { key, bytes } of AUTO_KEYS) {
    const fromEnv = process.env[key];
    if (!isPlaceholder(fromEnv)) {
      reused.push(key);
      // Keep a backup copy on disk if we don't already have one
      if (isPlaceholder(persisted[key])) {
        persisted[key] = String(fromEnv).trim();
        dirty = true;
      }
      continue;
    }

    if (!isPlaceholder(persisted[key])) {
      process.env[key] = String(persisted[key]).trim();
      reused.push(key);
      continue;
    }

    const value = generateSecret(bytes);
    process.env[key] = value;
    persisted[key] = value;
    generated.push(key);
    dirty = true;
  }

  if (dirty) {
    persisted._generatedAt = new Date().toISOString();
    persisted._note =
      'Auto-generated by RENACE deploy/runtime. Do not commit. Retrieve ADMIN_ACCESS_PASSWORD from this file if needed.';
    savePersisted(filePath, persisted);
  }

  if (generated.length) {
    console.log(`[SECRETS] Generados automáticamente: ${generated.join(', ')}`);
    console.log(`[SECRETS] Persistidos en ${filePath} (chmod 600). No se imprimen en logs.`);
  } else {
    console.log('[SECRETS] Secretos de seguridad listos (env o archivo persistido).');
  }

  return { generated, reused, file: filePath };
}

module.exports = {
  bootstrapSecrets,
  isPlaceholder,
  generateSecret,
  AUTO_KEYS,
};
